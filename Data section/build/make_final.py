"""make_final.py  merge-ready copy of the Data section (29 Oct 2026, Claude)

Reads   manuscript/data-section-draft.tex, manuscript/data-section-refs.bib
Writes  manuscript/data-section-final.tex   draft without review markup: \\evidence{} kept as comments,
                                            \\pcite -> \\parencite, \\draftnum{} unwrapped, review-marker comments
                                            dropped, preamble macros dropped (jair.cls defines \\Description)
        manuscript/data-section-final.bib   only the entries the final text cites
To merge (not done here; Toon 28 Oct: our part only): copy data-section-final.tex to sections/, add
\\input{sections/<name>} to main.tex, append data-section-final.bib to references.bib (skip keys already there),
copy manuscript/figures/data-difficulty.pdf to figures/ and change the \\includegraphics path to data-difficulty.
"""
import os, re
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(HERE)
src = open("manuscript/data-section-draft.tex", encoding="utf-8").read()
body = src[src.index("\\section{How the SMOTE Literature Uses Data}"):]

def unwrap(text, macro, fn):
    out, k = [], 0
    while True:
        m = text.find("\\" + macro + "{", k)
        if m < 0: out.append(text[k:]); return "".join(out)
        out.append(text[k:m]); q = m + len(macro) + 1; d = 0
        for t in range(q, len(text)):
            if text[t] == "{": d += 1
            elif text[t] == "}":
                d -= 1
                if d == 0: end = t; break
        out.append(fn(text[q + 1:end])); k = end + 1

body = unwrap(body, "evidence", lambda s: "% Evidence: " + re.sub(r"\s*\n\s*", "\n% ", s.strip()))
body = unwrap(body, "draftnum", lambda s: s)
body = body.replace("\\pcite{", "\\parencite{")
body = "\n".join(l for l in body.split("\n") if not l.startswith("% Claude 29 Oct 2026") and l.strip() != "%")
assert "\\claudedraft" not in body and "\\toon{" not in body and "\\pcite" not in body
head = ("% =====================================================================\n"
        "% Data section, merge-ready copy generated by Data section/build/make_final.py\n"
        "% from manuscript/data-section-draft.tex (do not edit here; edit the draft and rerun).\n"
        "% Sources of every number: the '% Evidence:' comments and Data section/handoff.md.\n"
        "% =====================================================================\n")
open("manuscript/data-section-final.tex", "w", encoding="utf-8").write(head + body)
keys = {k.strip() for g in re.findall(r"\\parencite\{([^}]+)\}", body) for k in g.split(",")}
bib = open("manuscript/data-section-refs.bib", encoding="utf-8").read()
entries = re.findall(r"(@\w+\{([^,]+),.*?\n\})", bib, re.S)
keep = [e for e, k in entries if k.strip() in keys]
missing = keys - {k.strip() for _, k in entries}
open("manuscript/data-section-final.bib", "w", encoding="utf-8").write(
    "% Entries cited by data-section-final.tex (generated by build/make_final.py from data-section-refs.bib)\n\n" + "\n\n".join(keep) + "\n")
print("cited", len(keys), "written", len(keep), "missing", sorted(missing))
