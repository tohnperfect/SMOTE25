"""Are the synthetic (author-generated) datasets published?  (8 Nov 2026, Claude; Toon asked, over all 76 papers)

Supersedes block 3 of build/name_level_extras.py (29 Oct), which used a keyword search and missed two statements:
k-means SMOTE ("All modified and simulated datasets used in the study are made available at https://github.com/...")
and CTGAN ("Our benchmark can be found at https://github.com/DAI-Lab/SDGym", the benchmark that contains its
7 simulated datasets). Both move from "not found" to "published".

Part A  the 120 dataset entries whose category is `synthetic` (19 papers) -> one availability group per paper.
Part B  papers whose full text describes author-generated data that were NOT recorded as dataset entries
        (illustrations or side experiments). Found with build/synthetic_scan.py over all 72 papers with experiments
        (ENN, AdaBoost and the Pradipta review have no data; Tomek Links has no PDF in out/pdf_map.json). Reported separately; the corpus counts are not
        changed (adding them as entries is a decision for Toon).

Groups (decided from the PDF text only):
  published        the paper gives a location for the synthetic data themselves
  cited source     the data were generated in another work, which the paper cites
  on request       the paper says data are available on request
  code link only   the paper links the method's code, not the data
  generator named  the generator is a public library call (e.g. scikit-learn make_moons), no data file
  not found        no statement on where the data can be obtained (the generation is described in the text)
Every evidence quote is asserted to occur in the PDF text (pdftotext, hyphenation at line ends removed,
whitespace collapsed). Run from Data section/ on the machine that holds paper/.
Output: out/synthetic_availability.json, out/synthetic_availability.csv
"""
import json, re, subprocess, csv
import pandas as pd

PM = json.load(open('out/pdf_map.json'))
KEYMAP = {'CTGAN / TVAE': 'CTGAN', 'Global-CS (AAAI)': 'Global-CS-AAAI', 'Global-CS (journal)': 'Global-CS-journal',
          'k-means SMOTE': 'k-means-SMOTE', 'RBBoost / Random Balance': 'RBBoost'}

def T(k):
    k = KEYMAP.get(k, k); t = ''
    for f in [PM[k]['main']] + list(PM[k].get('supp') or []):
        t += subprocess.run(['pdftotext', f, '-'], capture_output=True, text=True).stdout
    return re.sub(r'\s+', ' ', re.sub(r'-\n', '', t))

A = {  # paper_key: (group, evidence quote or None, page/location note)
 'G-SMOTE': ('published', 'can be found at https://github.com/IMS-ML-Lab', ''),
 'GMMSampling': ('published', 'the artificial datasets can be found in the repository of multi-imbalance', ''),
 'SVDD-WSMOTE': ('published', 'can be found in https://github.com/Zheng7777/simulated-datasets', ''),
 'SMOTE-IPF': ('published', 'This web-page also includes the basic information of this paper, the datasets used', ''),
 'k-means SMOTE': ('published', 'All modified and simulated datasets used in the study are made available at', 'corrected 8 Nov (was not found)'),
 'CTGAN / TVAE': ('published', 'Our benchmark can be found at https://github.com/DAI-Lab/SDGym', 'benchmark with 7 simulated datasets; corrected 8 Nov (was not found)'),
 'SOUP': ('cited source', 'synthetic data sets coming from the work of Lango et al. (2017)', ''),
 'Tomek Links': ('cited source', None, 'example from ref. [4] (Fig. 6 caption p.3; reading note)'),
 'NBU': ('code link only', 'Source code available at https://github.com/fonkafon/NB-undersampling', ''),
 'DLexiBoost': ('code link only', 'Our implementation of LexiBoost can be found at https://github.com/Shounak-D/LexiBoost', ''),
 'GOIO': ('code link only', 'The source code of GOIO is available', ''),
 'SPE': ('code link only', 'github.com/ZhiningLiu1998/self-paced-ensemble', ''),
 'ADASYN': ('not found', 'All data examples are generated by multidimensional Gaussian distributions', ''),
 'Borderline-SMOTE': ('not found', None, 'no availability sentence in the PDF'),
 'ClusterCentroids': ('not found', 'The synthetic datasets have two kinds of noisy data', ''),
 'Global-CS (AAAI)': ('not found', 'The synthetic ones are generated as follows', ''),
 'Global-CS (journal)': ('not found', None, 'same 6 synthetic sets as the AAAI version; no availability sentence'),
 'MWMOTE': ('not found', 'MWMOTE has been evaluated extensively on four artificial and 20 real-world data sets', ''),
 'SPIDER2': ('not found', 'We generated multiple data sets with diﬀerent numbers of examples', ''),
}
B = {  # paper_key: (group, sets as stated, role, evidence quotes)
 'COG-OS': ('not found', '3 two-class 2-D sets + 1 three-class set', 'illustration (Sec. 2.2, 3)',
            ['we generate synthetic data sets for three diﬀerent scenarios', 'we use a synthetic data set with three classes']),
 'LS': ('not found', 'artificial 2-D sets (Fig. 2)', 'side experiment on sampling levels',
        ['We consider this question by constructing some artificial datasets']),
 'MC-MBRC': ('on request', '50 artificial datasets (IR x overlap grid)', 'side experiment (Exp. 2, ablation)',
             ['The experiment was conducted on 50 artificial datasets', 'Data will be made available on request',
              'The code (and data) in this article has been certified as Reproducible by Code Ocean']),
 'NROMM': ('cited source', '4 simulated sets A-D from ref. [7] (2-D and 1-D versions)', 'side experiment (Sec. 8)',
           ['We refer four simulated datasets from [7]']),
 'RSMOTE': ('generator named', 'toy, moons, circles (2-D)', 'illustration (Figs. 2-5)',
            ['are generated by the Python library scikit-learn']),
 'MDO': ('not found', '1 five-class 2-D set', 'illustration (Figs. 4-5)', ['five-class artificial data set']),
 'MLOS': ('code link only', '1 set (560 majority / 35 minority)', 'illustration (Fig. 5)',
          ['Examples on synthetic dataset with 560 majority samples', 'The source code of MLOS is available at https://github.com/ytyancp/MLOS']),
 'RBBoost / Random Balance': ('not found', '1 set (two Gaussian classes, 450/50)', 'illustration (diversity study)',
                              ['We generated two 2-dimensional Gaussian classes']),
 'GDO': ('not found', '1 set (200/33)', 'illustration (Fig. 4)', ['The original artificial data set']),
 'OREM-M': ('not found', '1 simulated set (supplement Fig. S2); "Toy" in Table 6 is recorded as an entry with category original',
            'illustration', ['in this simulated dataset']),
}

def main():
    D = pd.read_csv('out/dataset_records.csv')   # includes the Tomek Links placeholder (1 synthetic entry, not named)
    S = D[D.category == 'synthetic']
    assert set(S.paper_key) == set(A), f'STOP: synthetic papers changed {set(S.paper_key) ^ set(A)}'
    rows = []
    for k, (g, ev, note) in A.items():
        if ev: assert ev in T(k), f'STOP: evidence not in PDF for {k}: {ev}'
        s = S[S.paper_key == k]
        rows.append(dict(part='A', paper=k, group=g, entries=len(s), names=s.normalized_name.nunique(), sets_stated='',
                         role='dataset entries', evidence=ev or note, note=note if ev else ''))
    for k, (g, sets, role, evs) in B.items():
        t = T(k)
        for ev in evs: assert ev in t, f'STOP: evidence not in PDF for {k}: {ev}'
        rows.append(dict(part='B', paper=k, group=g, entries=0, names=0, sets_stated=sets, role=role, evidence=' | '.join(evs), note=''))
    R = pd.DataFrame(rows)
    G = ['published', 'cited source', 'on request', 'code link only', 'generator named', 'not found']
    a = R[R.part == 'A']
    nm = lambda papers: int(S[S.paper_key.isin(papers)].normalized_name.nunique())
    out = dict(
        method='pdftotext of every PDF (main + supplement); evidence quotes asserted; Part B from build/synthetic_scan.py',
        corpus=dict(papers_total=76, papers_with_data=73, pdfs_scanned=len(PM), not_in_pdf_map='Tomek Links (synthetic example read from Fig. 6 caption, 18 Oct)', papers_with_synthetic_entries=int(a.paper.nunique()),
                    synthetic_entries=int(len(S)), synthetic_names=int(S.normalized_name.nunique())),
        part_A_by_group={x: dict(papers=int((a.group == x).sum()), entries=int(a[a.group == x].entries.sum()),
                                 names=nm(a[a.group == x].paper)) for x in G},
        part_A_published_vs_not=dict(
            published=dict(papers=int((a.group == 'published').sum()), entries=int(a[a.group == 'published'].entries.sum())),
            not_published_by_authors=dict(papers=int((a.group != 'published').sum()), entries=int(a[a.group != 'published'].entries.sum()),
                                          of_which_cited_source_entries=int(a[a.group == 'cited source'].entries.sum()))),
        part_B=dict(papers=int((R.part == 'B').sum()), by_group={x: int(((R.part == 'B') & (R.group == x)).sum()) for x in G}),
        rows=rows)
    assert sum(v['entries'] for v in out['part_A_by_group'].values()) == len(S)
    json.dump(out, open('out/synthetic_availability.json', 'w'), indent=1, ensure_ascii=False, default=int)
    R.to_csv('out/synthetic_availability.csv', index=False)
    print(json.dumps({k: v for k, v in out.items() if k != 'rows'}, indent=1, ensure_ascii=False, default=int))

if __name__ == '__main__':
    main()
