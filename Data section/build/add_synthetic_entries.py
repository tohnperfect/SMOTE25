def pdf_text(key, i, p):
    pm = json.load(open("out/pdf_map.json"))
    f = ([pm[key]["main"]] + list(pm[key].get("supp") or []))[i]
    t = subprocess.run(["pdftotext", "-f", str(p), "-l", str(p), f, "-"], capture_output=True, text=True).stdout
    return re.sub(r"\s+", " ", re.sub(r"-\n", "", t))

def check_pdf():
    n = 0
    for k, lst in NEW.items():
        for e in lst:
            i, p = e["page"]
            t = pdf_text(k, i, p)
            assert e["quote"] in t, f"STOP: quote not on {k} file {i} p.{p}: {e['quote']}"
            n += 1
    print("ok: all", n, "evidence quotes found on the cited page")

def rcsv(f): return list(csv.DictReader(open(f, encoding="utf-8-sig")))
def wcsv(f, rows):
    with open(f, "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)

def apply():
    old_full = rcsv("out/full_datasets.csv"); old_ver = rcsv("out/verify_datasets.csv"); old_vd = rcsv("out/verified_datasets.csv")
    assert len(old_full) == len(old_ver) == len(old_vd)
    added = 0
    for k, lst in list(NEW.items()) + [("OREM-M", None)]:
        f = f"ai-draft/full/{FILE.get(k, k)}.json"
        d = json.load(open(f, encoding="utf-8"))
        if lst is None:   # Toy: reader value unchanged; the category is an override in build/full_extraction.py (EXTERNAL)
            pass
        else:
            have = {x["name"] for x in d["datasets"]}
            for e in lst:
                if e["entry"]["name"] not in have: d["datasets"].append(e["entry"]); added += 1
        json.dump(d, open(f, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    r = subprocess.run([sys.executable, "build/full_extraction.py"], capture_output=True, text=True)
    assert r.returncode == 0, r.stderr[-2000:]
    new_full = rcsv("out/full_datasets.csv")
    # align: every old row must reappear in order; new rows are the Part-B names
    newkeys = {(k, e["entry"]["name"]) for k, lst in NEW.items() for e in lst}
    paper_of = {}
    for x in new_full: paper_of.setdefault(x["paper"], 0)
    vrows, vdrows, j = [], [], 0
    for x in new_full:
        pk = x["paper"]
        if (pk if pk != "RBBoost / Random Balance" else "RBBoost", x["name"]) in newkeys and not (
                j < len(old_full) and old_full[j]["paper"] == pk and old_full[j]["name"] == x["name"]):
            vrows.append(dict(paper=pk, name=x["name"], ref=x["ref"], status="ok (evidence quote, add_synthetic_entries.py)",
                              detail="quote asserted on the cited page; values are the printed ones"))
            vdrows.append({**x, "value_status": "verified against paper",
                           "verification": "PDF text layer: evidence quote found on the cited page (build/add_synthetic_entries.py --check-pdf)",
                           "verified_page": "", "verified_by": WHO})
            continue
        o = old_full[j]; assert (o["paper"], o["name"]) == (pk, x["name"]), (j, o["paper"], o["name"], pk, x["name"])
        if o != x: assert pk == "OREM-M" and x["name"] == "Toy", f"STOP: unexpected change in row {j}: {pk} {x['name']}"
        vrows.append(old_ver[j]); vdrows.append({**old_vd[j], **{c: x[c] for c in x}}); j += 1
    assert j == len(old_full)
    wcsv("out/verify_datasets.csv", vrows); wcsv("out/verified_datasets.csv", vdrows)
    # the Toy outcome row carries the dataset's category: copy the override into verified_outcomes.csv (only these 2 fields)
    toy = [x for x in new_full if x["paper"] == "OREM-M" and x["name"] == "Toy"][0]
    vo = rcsv("out/verified_outcomes.csv"); hit = 0
    for r in vo:
        if r["paper"] == "OREM-M" and r["dataset"] == "Toy (Toy)":
            r["how_obtained"], r["how_basis"] = toy["how_obtained_final"], toy["how_basis"]; hit += 1
    assert hit == 1; wcsv("out/verified_outcomes.csv", vo)
    print("added", added, "entries; full_datasets", len(old_full), "->", len(new_full))

if __name__ == "__main__":
    if "--check-pdf" in sys.argv: check_pdf()
    elif "--apply" in sys.argv: apply()
    else: print(__doc__)
