"""Add the author-generated (synthetic) data of the 10 "Part B" papers as dataset entries, and re-categorise OREM-M "Toy"
(8 Nov 2026, Claude; Toon: "อีก 10 paper สร้างข้อมูลเองเพื่อใช้ประกอบภาพหรือทดลองข้างเคียง ให้นับลงใน entry เลย" and
"Toy ของ OREM-M ... ต้องลองตรวจสอบดีๆ").

Part B = the papers found by build/synthetic_scan.py whose text describes data the authors generated for an illustration or
a side experiment, but which were not recorded as dataset entries on 18 Oct (build/synthetic_availability.py, dict B).
One entry per generated data set, the same granularity as the synthetic entries already in the corpus (e.g. SPIDER2
records each of its 24 generated sets). Values are only what the paper prints; sums and values derived from a printed
ratio are not filled in (they are written in how_obtained_detail instead). in_results_table = "no" because none of these
sets is in a results table that has both the proposed method and SMOTE (they are in figures or side tables).
Names: the papers do not name most of these sets, so the entry names are descriptive and chosen so that the name rules
(build/family_rule.py; parentheses are dropped by the name normaliser) do not join them with unrelated sets.
Two papers re-use sets of another corpus paper and keep its names, so they join the same name: NROMM's sets A-D are the
"simulated dataset A-D" of SVDD-WSMOTE (its ref. [7]); RSMOTE's moons and circles are those of k-means SMOTE (its ref. [10]).

Entries are APPENDED after each paper's existing entries, so every existing record_id (paper_id-D<ordinal>) is unchanged.

Modes (run from Data section/):
  python3 build/add_synthetic_entries.py --check-pdf   on the machine that holds paper/: assert every evidence quote
                                                       occurs on the cited PDF page (pdftotext, whitespace collapsed)
  python3 build/add_synthetic_entries.py --apply       edit ai-draft/full/<KEY>.json (the originals are in git history;
                                                       the backup folder was removed 9 Nov),
                                                       rerun build/full_extraction.py, then insert the new rows into
                                                       out/verify_datasets.csv and out/verified_datasets.csv at the same
                                                       positions (existing rows unchanged, except Toy's how_obtained fields)
Idempotent: an entry whose name already exists in the paper's JSON is not added again.

OREM-M "Toy" (Table 6, p.11): the paper gives no source for it (reader: "not stated"; rule 2 of 18 Oct made it "original").
Checked outside the paper: "toy" is the synthetic data set of the ordinal-regression benchmark (Gutierrez et al. 2016,
IEEE TKDE 28(1):127-146, Table 3: 300 patterns, 2 attributes, 5 classes, distribution 35/87/79/68/31). The public ORCA
copy (github.com/ayrna/orca, exampledata/1-holdout/toy, train 225 + test 75 rows, commit 7940028) has 300 rows, 2 features
and class counts 35/87/79/68/31, the same five counts as OREM-M Table 6 (68/87/79/35/31, printed in another class order).
Nothing was removed or relabelled, so it is not "modified"; it is a published synthetic set -> how_obtained_final = synthetic.
Because this evidence is outside the paper, the reader's value in OREM-M.json stays "not stated" and the category is set by
the EXTERNAL override in build/full_extraction.py (how_basis says "external check 8 Nov").
"""
