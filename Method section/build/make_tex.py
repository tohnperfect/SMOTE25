"""Generate LaTeX fragments for the SMOTE-family draft from the Method Map:
  generated/smote-family-table.tex   one row per SMOTE-family paper (category + six steps)
  generated/smote-family-methods.tex per-method account (how it builds on SMOTE, class evidence)
Usage: make_tex.py MAP OUTDIR"""
import json, re, sys, os

src = open(sys.argv[1], encoding='utf-8').read()
D = json.loads(re.search(r'<script type="application/json" id="data">(.*?)</script>', src, flags=re.S).group(1))
SF = sorted([p for p in D if p['smote_based']], key=lambda p: (p['year'], p['acronym'].lower()))
assert len(SF) == 37

KEY = {'SMOTE': 'chawla2002smote', 'SMOTEBoost': 'chawla2003smoteboost', 'SMOTE-Tomek / SMOTE-ENN': 'batista2004study',
       'Borderline-SMOTE': 'han2005borderline', 'Cluster-SMOTE': 'cieslak2006cluster', 'ADASYN': 'he2008adasyn',
       'LS': 'cieslak2008ls', 'Safe-Level-SMOTE': 'bunkhumpornpat2009safelevel', 'RAMOBoost': 'chen2010ramoboost',
       'DSRBF / SSRBF (Static-SMOTE)': 'fernandeznavarro2011dsrbf', 'INOS': 'cao2013inos', 'MWMOTE': 'barua2014mwmote',
       'RBBoost': 'diezpastor2015randombalance', 'SCUT': 'agrawal2015scut', 'SMOTE-IPF': 'saez2015smoteipf',
       'A-SUWO': 'nekooeimehr2016asuwo', 'CGMOS': 'zhang2016cgmos', 'SMOM': 'zhu2017smom', 'k-means SMOTE': 'douzas2018kmeans',
       'G-SMOTE': 'douzas2019gsmote', 'GAMO': 'mullick2019gamo', 'AB-SMOTE': 'almajzoub2020absmote', 'EMDO': 'yao2021emdo',
       'HDE': 'chen2021hde', 'RSMOTE': 'chen2021rsmote', 'FW-SMOTE': 'maldonado2022fwsmote', 'KNNOR': 'islam2022knnor',
       'SVDDWSMOTE': 'tao2022svddw', 'GLOS': 'han2023glos', 'NROMM': 'liu2023nromm', 'OREM / OREM-M': 'zhu2023orem',
       'MC-MBRC': 'ma2024mcmbrc', 'MKC-SMOTE': 'wang2024mkc', 'GDHS': 'yan2025gdhs', 'CISO': 'yadav2025ciso',
       'Loyalty-SMOTE': 'hu2026loyalty', 'QC-SMOTE': 'upman2026qcsmote'}
NAME = {'SMOTE-Tomek / SMOTE-ENN': 'SMOTE-Tomek, SMOTE-ENN', 'DSRBF / SSRBF (Static-SMOTE)': 'SSRBF, DSRBF',
        'OREM / OREM-M': 'OREM, OREM-M', 'SVDDWSMOTE': 'SVDD-WSMOTE'}
CAT = {'Binary only': 'B', 'Multiclass only': 'M', 'Binary + Multiclass': 'B+M'}
STEPS = ['Seed selection', 'Sample allocation', 'Neighbour choice', 'Placement rule', 'Post-filtering', 'Inside a pipeline']
PROVISIONAL = {'P74', 'P62'}
assert set(KEY) == {p['acronym'] for p in SF}

BS = chr(92)
def esc(s):
    s = s.replace(BS, '').replace('’', "'").replace('‘', "'")
    for a, b in [('&', BS + '&'), ('%', BS + '%'), ('#', BS + '#'), ('_', BS + '_'), ('{', BS + '{'), ('}', BS + '}'),
                 ('~', '$' + BS + 'sim$'), ('^', BS + '^{}'), ('<', '$<$'), ('>', '$>$')]:
        s = s.replace(a, b)
    return s

def esc_math(s):
    """Escape, then typeset short symbols such as x_i, alpha_r, lambda as math."""
    s = s.replace('’', "'").replace('‘', "'")
    out = []
    for tok in re.split(r'(\balpha_\w+|\b[A-Za-z]_\w+\b|\blambda\b|\balpha\b)', s):
        if re.fullmatch(r'alpha_(\w+)', tok):
            out.append('$' + BS + 'alpha_{' + tok[6:] + '}$')
        elif re.fullmatch(r'[A-Za-z]_\w+', tok):
            a, b = tok.split('_', 1)
            out.append('$' + a + '_{' + b.replace('_', '') + '}$')
        elif tok in ('lambda', 'alpha'):
            out.append('$' + BS + tok + '$')
        else:
            out.append(esc(tok))
    return ''.join(out).replace('$ $', ' ')

name = lambda p: esc(NAME.get(p['acronym'], p['acronym']))
os.makedirs(sys.argv[2], exist_ok=True)

# table rows
rows = ['%% Generated by make_tex.py from SMOTE25_Method_Map_1.html (28 Oct 2026). Do not edit by hand.',
        BS + 'begin{tabular}{@{}p{0.33' + BS + 'linewidth}cclcccccc@{}}', BS + 'toprule',
        'Method & Year & Class & Link & Seed & Alloc. & Nbr. & Place & Filter & Pipe' + BS + BS, BS + 'midrule']
for p in SF:
    marks = ' & '.join(BS + 'fm' if s in p['smote_via'] else '' for s in STEPS)
    cat = CAT[p['class_category']] + ('*' if p['uid'] in PROVISIONAL else '')
    rows.append('%s~%s{%s} & %d & %s & %s & %s %s%s' % (
        name(p), BS + ('parencite' if p['acronym'] == 'SMOTE' else 'pcite'), KEY[p['acronym']], p['year'],
        cat, p['smote_rel'], marks, BS, BS))
tot = [sum(s in p['smote_via'] for p in SF) for s in STEPS]
rows.append(BS + 'addlinespace')
rows.append('Total (37) & & & & ' + ' & '.join(map(str, tot)) + ' ' + BS + BS)
rows += [BS + 'bottomrule', BS + 'end{tabular}']
open(os.path.join(sys.argv[2], 'smote-family-table.tex'), 'w', encoding='utf-8', newline='\n').write('\n'.join(rows) + '\n')

# per-method accounts, grouped by class category
out = ['%% Generated by make_tex.py from SMOTE25_Method_Map_1.html (28 Oct 2026). Do not edit by hand.',
       '%% Each account was written from a full reading of the PDF on 28 Oct 2026 (AI reader); check against the paper.']
for cat in ['Binary only', 'Multiclass only', 'Binary + Multiclass']:
    ps = [p for p in SF if p['class_category'] == cat]
    out.append(BS + 'subsection{%s (%d Methods)}' % (cat, len(ps)))
    out.append(BS + 'label{sec:methods-%s}' % CAT[cat].replace('+', ''))
    out.append(BS + 'begin{description}')
    for p in ps:
        cite = BS + ('parencite' if p['acronym'] == 'SMOTE' else 'pcite') + '{' + KEY[p['acronym']] + '}'
        steps = ', '.join(p['smote_via']) if p['smote_via'] else 'none (the reference rule)'
        out.append('%sitem[%s (%d)] %s %s' % (BS, name(p), p['year'], cite, esc_math(p['smote_explain'])))
        out.append('  %stextit{Steps changed:} %s.' % (BS, esc(steps)))
        ev = esc(p['class_evidence_pdf'])
        if p['class_reduced']:
            ev += ' ' + BS + 'textit{Reduction:} ' + esc(p['class_reduced'])
        if p['class_multiclass_how']:
            ev += ' ' + BS + 'textit{Several classes:} ' + esc(p['class_multiclass_how'])
        out.append('  %sclassev{%s}' % (BS, ev))
        if p['uid'] in PROVISIONAL or p['acronym'] in ('OREM / OREM-M', 'NROMM', 'SMOM'):
            out.append('  %spnote{%s}' % (BS, esc(p['pdf_check_note'])))
    out.append(BS + 'end{description}')
open(os.path.join(sys.argv[2], 'smote-family-methods.tex'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('totals', tot)
